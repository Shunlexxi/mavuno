export const getProductsByCategory = (category: ProductCategory): Product[] => {
  return products.filter((p) => p.category === category) as Product[];
};

export const getFeaturedProducts = (): Product[] => {
  return products.filter((p) => p.isFeatured) as Product[];
};

export const getProductById = (id: string): Product | RentalProduct | undefined => {
  return products.find((p) => p.id === id);
};

export const getAllProducts = (): Product[] => {
  return products as Product[];
};

export const searchProducts = (query: string): Product[] => {
  const lowerQuery = query.toLowerCase();
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(lowerQuery) ||
      p.description.toLowerCase().includes(lowerQuery) ||
      p.merchant.name.toLowerCase().includes(lowerQuery)
  ) as Product[];
};

